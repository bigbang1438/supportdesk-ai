CREATE TABLE IF NOT EXISTS assistant_runs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id BIGINT NOT NULL REFERENCES tenants(id), actor_id BIGINT NOT NULL REFERENCES users(id),
 ticket_id BIGINT NOT NULL REFERENCES tickets(id), ticket_version INT NOT NULL,
 state VARCHAR(20) NOT NULL CHECK(state IN ('none','pending','published','discarded')),
 view_json CLOB NOT NULL, created_at VARCHAR(40) NOT NULL, expires_at VARCHAR(40)
);
CREATE INDEX IF NOT EXISTS idx_assistant_actor_ticket ON assistant_runs(tenant_id,actor_id,ticket_id,id);
