CREATE TABLE IF NOT EXISTS tenants (id BIGINT PRIMARY KEY, name VARCHAR(100) NOT NULL);
CREATE TABLE IF NOT EXISTS users (
 id BIGINT PRIMARY KEY, tenant_id BIGINT NOT NULL REFERENCES tenants(id),
 username VARCHAR(60) NOT NULL UNIQUE, display_name VARCHAR(100) NOT NULL,
 role VARCHAR(20) NOT NULL CHECK (role IN ('customer','agent')), password_hash VARCHAR(100) NOT NULL
);
CREATE TABLE IF NOT EXISTS support_orders (
 id BIGINT PRIMARY KEY,tenant_id BIGINT NOT NULL REFERENCES tenants(id),customer_id BIGINT NOT NULL REFERENCES users(id),
 order_number VARCHAR(40) NOT NULL UNIQUE,item_name VARCHAR(120) NOT NULL,quantity INT NOT NULL CHECK(quantity>0),
 total_cents INT NOT NULL CHECK(total_cents>=0),status VARCHAR(20) NOT NULL CHECK(status IN ('paid','shipped','delivered','cancelled')),updated_at VARCHAR(24) NOT NULL
);
CREATE TABLE IF NOT EXISTS tickets (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,tenant_id BIGINT NOT NULL REFERENCES tenants(id),customer_id BIGINT NOT NULL REFERENCES users(id),order_id BIGINT NOT NULL REFERENCES support_orders(id),
 ticket_number VARCHAR(40) NOT NULL UNIQUE,subject VARCHAR(100) NOT NULL,body VARCHAR(2000) NOT NULL,
 status VARCHAR(20) NOT NULL CHECK(status IN ('open','processing','resolved')),version INT NOT NULL DEFAULT 0,created_at VARCHAR(24) NOT NULL,updated_at VARCHAR(24) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_orders_scope ON support_orders(tenant_id,customer_id,updated_at,id);
CREATE INDEX IF NOT EXISTS idx_tickets_scope ON tickets(tenant_id,customer_id,status,updated_at,id);
CREATE TABLE IF NOT EXISTS ticket_messages (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,ticket_id BIGINT NOT NULL REFERENCES tickets(id),author_id BIGINT NOT NULL REFERENCES users(id),body VARCHAR(1500) NOT NULL,created_at VARCHAR(24) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_messages_ticket ON ticket_messages(ticket_id,id);
CREATE TABLE IF NOT EXISTS ticket_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,ticket_id BIGINT NOT NULL REFERENCES tickets(id),actor_id BIGINT NOT NULL REFERENCES users(id),action VARCHAR(30) NOT NULL,detail VARCHAR(300) NOT NULL,created_at VARCHAR(24) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_events_ticket ON ticket_events(ticket_id,id);
CREATE TABLE IF NOT EXISTS policies (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,tenant_id BIGINT NOT NULL REFERENCES tenants(id),title VARCHAR(100) NOT NULL,filename VARCHAR(80) NOT NULL,
 content VARCHAR(4000) NOT NULL,version INT NOT NULL DEFAULT 0,updated_at VARCHAR(24) NOT NULL,UNIQUE(tenant_id,filename)
);
